export async function download10VariantsZip(
  domain: string,
  variants: LogoVariant[]
): Promise<void> {
  const zip = new JSZip();
  const baseName = domain.replace(/[^a-z0-9]/gi, '-').toLowerCase();

  for (const v of variants) {
    await ensureFontLoaded(v.fontFamily);
    const folder = zip.folder(`concept-${v.id}-${v.activeIcon.toLowerCase()}`);
    if (!folder) continue;

    const svgMain = generateFullLogoSvg(v, { width: 1500, height: 900, background: 'white' });
    const svgSquare = generateFullLogoSvg(v, { width: 1200, height: 1200, background: 'white' });
    const emblemSvg = buildEmblemSvgMarkup(
      {
        containerStyle: v.containerStyle,
        construction: v.construction,
        activeIcon: v.activeIcon,
        secondaryIcon: v.secondaryIcon,
        emblemFusion: v.emblemFusion,
        customSvgPath: v.customSvgPath,
        primary: v.primary,
        secondary: v.secondary,
        accent: v.accent,
        fontFamily: v.fontFamily,
        word1: v.word1,
      },
      200
    );

    folder.file(`${baseName}-concept-${v.id}-1500x900.svg`, svgMain);
    folder.file(`${baseName}-concept-${v.id}-1200x1200.svg`, svgSquare);
    folder.file(`${baseName}-concept-${v.id}-emblem.svg`, emblemSvg);

    try {
      const iconImg = await loadSvgToImage(emblemSvg);

      const cMain = document.createElement('canvas');
      drawLogoOnCanvas(cMain, iconImg, v, 750, 450, false, false, 2);
      const mainData = cMain.toDataURL('image/png', 1.0).split(',')[1];
      folder.file(`${baseName}-concept-${v.id}-1500x900.png`, mainData, { base64: true });

      const cSq = document.createElement('canvas');
      drawLogoOnCanvas(cSq, iconImg, v, 600, 600, true, false, 2);
      const sqData = cSq.toDataURL('image/png', 1.0).split(',')[1];
      folder.file(`${baseName}-concept-${v.id}-1200x1200.png`, sqData, { base64: true });
    } catch {
      // Continue if canvas image conversion fails
    }
  }

  const content = await zip.generateAsync({ type: 'blob' });
  downloadBlob(content, `${baseName}-10-Vector-Concepts.zip`);
}

