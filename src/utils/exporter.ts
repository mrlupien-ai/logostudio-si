export function buildAppIconVariantSvg(
  state: LogoState,
  surface: 'primary' | 'white' | 'accent' | 'dark',
  size = 512
): string {
  let markColor = '#FFFFFF';
  let bgFillMarkup = `<rect x="0" y="0" width="${size}" height="${size}" rx="${Math.round(
    size * 0.225
  )}" fill="${state.primary}" />`;

  if (surface === 'white') {
    markColor = wcagContrastRatio(state.primary, '#FFFFFF') >= 2.5 ? state.primary : '#0F172A';
    bgFillMarkup = `<rect x="0" y="0" width="${size}" height="${size}" rx="${Math.round(
      size * 0.225
    )}" fill="#FFFFFF" stroke="#E2E8F0" stroke-width="4" />`;
  } else if (surface === 'accent') {
    markColor = '#FFFFFF';
    bgFillMarkup = `<defs><linearGradient id="app-acc-grad" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${state.secondary}"/><stop offset="100%" stop-color="${state.primary}"/></linearGradient></defs><rect x="0" y="0" width="${size}" height="${size}" rx="${Math.round(
      size * 0.225
    )}" fill="url(#app-acc-grad)" />`;
  } else if (surface === 'dark') {
    markColor = wcagContrastRatio(state.secondary, '#0B0F19') >= 2.8 ? state.secondary : '#F8FAFC';
    bgFillMarkup = `<rect x="0" y="0" width="${size}" height="${size}" rx="${Math.round(
      size * 0.225
    )}" fill="#0B0F19" stroke="${state.secondary}" stroke-opacity="0.35" stroke-width="4" />`;
  } else {
    markColor = wcagContrastRatio('#FFFFFF', state.primary) >= 2.5 ? '#FFFFFF' : '#0F172A';
  }

  const innerMark = buildEmblemInnerMarkup({
    containerStyle: state.containerStyle,
    construction: state.construction,
    activeIcon: state.activeIcon,
    secondaryIcon: state.secondaryIcon,
    emblemFusion: state.emblemFusion,
    customSvgPath: state.customSvgPath,
    primary: state.primary,
    secondary: state.secondary,
    accent: state.accent,
    fontFamily: state.fontFamily,
    word1: state.word1,
    iconStrokeWidth: state.iconStrokeWidth,
    iconRotation: state.iconRotation,
    iconFlipH: state.iconFlipH,
    iconFlipV: state.iconFlipV,
    markOnly: true,
    markColor,
  });

  const scale = (size * 0.72) / 200;
  const offset = Math.round((size - 200 * scale) / 2);

  return `<!-- Generated by LogoStudio.si -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}">
  ${bgFillMarkup}
  <g transform="translate(${offset}, ${offset}) scale(${scale.toFixed(4)})">
    ${innerMark}
  </g>
</svg>`;
}

export async function downloadAppIconsZip(state: LogoState): Promise<void> {
  const zip = new JSZip();
  const baseName = (state.domain || 'app').replace(/[^a-z0-9]/gi, '-').toLowerCase();
  const surfaces: ('primary' | 'white' | 'accent' | 'dark')[] = [
    'primary',
    'white',
    'accent',
    'dark',
  ];

  for (const surf of surfaces) {
    const svg512 = buildAppIconVariantSvg(state, surf, 512);
    zip.file(`${baseName}-app-icon-${surf}.svg`, svg512);
    const png512 = await renderSvgToPngDataUrl(svg512, 512, 512);
    zip.file(`${baseName}-app-icon-${surf}-512x512.png`, png512.split(',')[1], { base64: true });
  }

  const fav = await generateFaviconAssets(state);
  zip.file('favicon.svg', fav.faviconSvg);
  zip.file('apple-touch-icon-180x180.png', fav.png180.split(',')[1], { base64: true });
  zip.file('favicon-32x32.png', fav.png32.split(',')[1], { base64: true });
  zip.file('favicon-16x16.png', fav.png16.split(',')[1], { base64: true });
  zip.file('site.webmanifest', fav.manifestJson);

  const blob = await zip.generateAsync({ type: 'blob' });
  downloadBlob(blob, `${baseName}-App-Icons-Suite.zip`);
}

