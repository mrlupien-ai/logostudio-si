export async function copySvgToClipboard(svgContent: string): Promise<boolean> {
  const withComment = svgContent.includes('Generated by LogoStudio.si')
    ? svgContent
    : `<!-- Generated by LogoStudio.si -->\n${svgContent}`;
  try {
    await navigator.clipboard.writeText(withComment);
    return true;
  } catch {
    const textarea = document.createElement('textarea');
    textarea.value = withComment;
    document.body.appendChild(textarea);
    textarea.select();
    document.execCommand('copy');
    document.body.removeChild(textarea);
    return true;
  }
}

