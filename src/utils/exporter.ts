export async function downloadPortfolioBatchZip(
  domains: string[],
  buildVariantForDomain: (domain: string) => LogoVariant,
  onProgress?: (current: number, total: number, domain: string) => void,
  isCancelled?: () => boolean
): Promise<boolean> {
  const zip = new JSZip();
  const total = domains.length;

  for (let i = 0; i < total; i++) {
    if (isCancelled && isCancelled()) {
      return false;
    }

    const dom = domains[i];
    if (onProgress) {
      onProgress(i + 1, total, dom);
    }

    // Yield to browser UI thread between domains
    await new Promise<void>((resolve) => requestAnimationFrame(() => resolve()));

    const variant = buildVariantForDomain(dom);
    await ensureFontLoaded(variant.fontFamily);

    const slug = dom.replace(/[^a-z0-9]/gi, '-').toLowerCase();
    const folder = zip.folder(slug);
    if (!folder) continue;

    const svgHorizontal = await generateFullLogoSvgEmbedded(variant, {
      width: 1500,
      height: 900,
      background: 'white',
    });
    const emblemSvg = buildEmblemSvgMarkup(
      {
        containerStyle: variant.containerStyle,
        construction: variant.construction,
        activeIcon: variant.activeIcon,
        secondaryIcon: variant.secondaryIcon,
        emblemFusion: variant.emblemFusion,
        customSvgPath: variant.customSvgPath,
        primary: variant.primary,
        secondary: variant.secondary,
        accent: variant.accent,
        fontFamily: variant.fontFamily,
        word1: variant.word1,
      },
      200
    );

    folder.file(`${slug}-horizontal.svg`, svgHorizontal);
    folder.file(`${slug}-emblem.svg`, emblemSvg);

    try {
      const iconImg = await loadSvgToImage(emblemSvg);

      const cMain = document.createElement('canvas');
      drawLogoOnCanvas(cMain, iconImg, variant, 750, 450, false, false, 2);
      const mainData = cMain.toDataURL('image/png', 1.0).split(',')[1];
      folder.file(`${slug}-1500x900.png`, mainData, { base64: true });

      const cSq = document.createElement('canvas');
      drawLogoOnCanvas(cSq, iconImg, variant, 600, 600, true, false, 2);
      const sqData = cSq.toDataURL('image/png', 1.0).split(',')[1];
      folder.file(`${slug}-1200x1200.png`, sqData, { base64: true });
    } catch {
      // Ignore canvas fallback error
    }

    const report = evaluateDomainBrandability(
      dom,
      variant.word1,
      variant.word2,
      variant.ext,
      'Brand Identity'
    );
    folder.file(
      'brand-tokens.json',
      JSON.stringify(
        {
          domain: dom,
          word1: variant.word1,
          word2: variant.word2,
          ext: variant.ext,
          fontFamily: variant.fontFamily,
          colors: {
            primary: variant.primary,
            secondary: variant.secondary,
            accent: variant.accent,
          },
          icon: variant.activeIcon,
          construction: variant.construction?.label || variant.containerStyle,
          brandIndex: report.brandIndex,
          marketTier: report.marketTier,
        },
        null,
        2
      )
    );
  }

  if (isCancelled && isCancelled()) {
    return false;
  }

  const yyyymmdd = new Date().toISOString().slice(0, 10).replace(/-/g, '');
  const content = await zip.generateAsync({ type: 'blob' });
  downloadBlob(content, `LogoStudio-Batch-${yyyymmdd}.zip`);
  return true;
}
