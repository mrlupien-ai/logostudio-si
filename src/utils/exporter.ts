export function downloadDataUrl(dataUrl: string, filename: string) {
  const link = document.createElement('a');
  link.href = dataUrl;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

export function downloadBlob(blob: Blob, filename: string) {
  const url = URL.createObjectURL(blob);
  downloadDataUrl(url, filename);
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export function downloadCanvasAsPng(canvas: HTMLCanvasElement, filename: string) {
  const dataUrl = canvas.toDataURL('image/png', 1.0);
  downloadDataUrl(dataUrl, filename);
}

export function downloadSvgFile(svgContent: string, filename: string) {
  const withComment = svgContent.includes('Generated by LogoStudio.si')
    ? svgContent
    : `<!-- Generated by LogoStudio.si -->\n${svgContent}`;
  const blob = new Blob([withComment], { type: 'image/svg+xml;charset=utf-8' });
  downloadBlob(blob, filename);
}

